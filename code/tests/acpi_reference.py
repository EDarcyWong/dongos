"""Independent physical-byte ACPI reference for the P3 QEMU oracle.

``discover(read, rsdp)`` returns the logical firmware inventory: integer fields,
three GAS dictionaries, and populated record lists (no unused-slot padding).
``read(pa, size)`` must return exactly those stable physical bytes. The caller
owns stopping the guest, checking RAM ownership, and recording every read.

Layouts are handwritten from ACPI 6.6 sections 5.2.5--5.2.12, Intel HPET 1.0a
section 3.2.4, and PCI Firmware MCFG declarations in official EDK2. Nothing is
imported from, generated by, or evaluated through the Dong implementation.
This is an inventory oracle, not an AML interpreter or MMIO access layer.
"""

from __future__ import annotations

import hashlib
import struct
from collections.abc import Callable


class AcpiError(ValueError):
    """Invalid or unsupported physical ACPI inventory."""


PhysicalReader = Callable[[int, int], bytes]
MAX_READ = 1 << 20
MAX_TABLES = 256
MAX_TOTAL_BYTES = 16 << 20
PHYSICAL_END = 1 << 32

_SCALARS = (
    "rsdp", "xsdt", "madt", "fadt", "hpet", "mcfg",
    "rsdp_revision", "table_count", "lapic_address", "madt_flags",
    "cpu_count", "ioapic_count", "iso_count", "nmi_count", "mcfg_count",
    "fadt_revision", "fadt_flags", "sci_interrupt", "boot_arch",
    "dsdt", "pm_timer_block", "pm_timer_length", "pm_timer_32bit",
    "reset_value", "hpet_id", "hpet_number", "hpet_min_tick",
    "hpet_page_protection",
)


def _gas(table: bytes, offset: int) -> dict[str, int]:
    if offset + 12 > len(table):
        return dict(address_space=0, bit_width=0, bit_offset=0,
                    access_size=0, address=0)
    space, width, bit_offset, access, address = struct.unpack_from("<BBBBQ", table, offset)
    return dict(address_space=space, bit_width=width, bit_offset=bit_offset,
                access_size=access, address=address)


def _u16(data: bytes, offset: int) -> int:
    return struct.unpack_from("<H", data, offset)[0]


def _u32(data: bytes, offset: int) -> int:
    return struct.unpack_from("<I", data, offset)[0]


def _u64(data: bytes, offset: int) -> int:
    return struct.unpack_from("<Q", data, offset)[0]


class _Discovery:
    def __init__(self, read: PhysicalReader):
        self.reader = read
        self.total_bytes = 0
        self.tables: list[dict[str, int | str]] = []
        self.inventory: dict = dict.fromkeys(_SCALARS, 0)
        self.inventory.update(pm_timer_gas=_gas(b"", 0),
                              reset_gas=_gas(b"", 0), hpet_gas=_gas(b"", 0),
                              cpus=[], ioapics=[], isos=[], nmis=[], mcfg_regions=[])

    def read(self, address: int, size: int) -> bytes:
        if (type(address) is not int or type(size) is not int or address <= 0
                or size <= 0 or size > MAX_READ
                or address >= PHYSICAL_END or size > PHYSICAL_END - address):
            raise AcpiError(f"physical read outside bounded low-4GiB range: {address!r}, {size!r}")
        self.total_bytes += size
        if self.total_bytes > MAX_TOTAL_BYTES:
            raise AcpiError("ACPI reads exceed total byte budget")
        try:
            raw = self.reader(address, size)
        except AcpiError:
            raise
        except Exception as error:
            raise AcpiError(f"physical reader failed at {address:#x}+{size:#x}: {error}") from error
        if not isinstance(raw, (bytes, bytearray, memoryview)) or len(raw) != size:
            raise AcpiError(f"short/non-byte physical read at {address:#x}, expected {size} bytes")
        return bytes(raw)

    def remember(self, address: int, raw: bytes, signature: str) -> None:
        self.tables.append(dict(physical=address, length=len(raw), signature=signature,
                                sha256=hashlib.sha256(raw).hexdigest()))

    def sdt(self, address: int) -> bytes:
        header = self.read(address, 36)
        length = _u32(header, 4)
        if length < 36 or length > MAX_READ:
            raise AcpiError(f"invalid SDT length {length} at {address:#x}")
        raw = self.read(address, length)
        if raw[:36] != header:
            raise AcpiError("SDT header changed between physical reads")
        if sum(raw) & 255:
            raise AcpiError(f"SDT checksum mismatch for {raw[:4]!r} at {address:#x}")
        self.remember(address, raw, raw[:4].decode("ascii", errors="backslashreplace"))
        return raw

    def madt(self, raw: bytes) -> None:
        if len(raw) < 44:
            raise AcpiError("MADT shorter than fixed header")
        inv = self.inventory
        inv["lapic_address"] = _u32(raw, 36)
        inv["madt_flags"] = _u32(raw, 40)
        override = False
        offset = 44
        minimum = {0: 8, 1: 12, 2: 10, 3: 8, 4: 6, 5: 12, 9: 16, 10: 12}
        while offset < len(raw):
            if len(raw) - offset < 2:
                raise AcpiError("MADT has truncated subtable header")
            kind, size = raw[offset:offset + 2]
            if size < 2 or size > len(raw) - offset or size < minimum.get(kind, 2):
                raise AcpiError(f"MADT type {kind} has invalid length {size}")
            entry = raw[offset:offset + size]
            if kind == 0:
                inv["cpus"].append(dict(kind=0, uid=entry[2], apic_id=entry[3], flags=_u32(entry, 4)))
            elif kind == 1:
                inv["ioapics"].append(dict(id=entry[2], address=_u32(entry, 4), gsi_base=_u32(entry, 8)))
            elif kind == 2:
                inv["isos"].append(dict(bus=entry[2], source=entry[3], gsi=_u32(entry, 4), flags=_u16(entry, 8)))
            elif kind == 3:
                inv["nmis"].append(dict(kind=3, processor=0, flags=_u16(entry, 2), lint=0, gsi=_u32(entry, 4)))
            elif kind == 4:
                inv["nmis"].append(dict(kind=4, processor=entry[2], flags=_u16(entry, 3), lint=entry[5], gsi=0))
            elif kind == 5:
                if override:
                    raise AcpiError("multiple local APIC address overrides")
                inv["lapic_address"] = _u64(entry, 4)
                override = True
            elif kind == 9:
                inv["cpus"].append(dict(kind=9, uid=_u32(entry, 12), apic_id=_u32(entry, 4), flags=_u32(entry, 8)))
            elif kind == 10:
                inv["nmis"].append(dict(kind=10, processor=_u32(entry, 4), flags=_u16(entry, 2), lint=entry[8], gsi=0))
            offset += size
        for key, records in (("cpu_count", "cpus"), ("ioapic_count", "ioapics"),
                             ("iso_count", "isos"), ("nmi_count", "nmis")):
            inv[key] = len(inv[records])

    def fadt(self, raw: bytes) -> None:
        if len(raw) < 116:
            raise AcpiError("FADT lacks the 116-byte legacy prefix")
        inv = self.inventory
        inv.update(fadt_revision=raw[8], fadt_flags=_u32(raw, 112),
                   sci_interrupt=_u16(raw, 46), boot_arch=_u16(raw, 109),
                   dsdt=_u32(raw, 40), pm_timer_block=_u32(raw, 76),
                   pm_timer_length=raw[91], pm_timer_32bit=(_u32(raw, 112) >> 8) & 1,
                   pm_timer_gas=_gas(raw, 208), reset_gas=_gas(raw, 116))
        if len(raw) >= 129:
            inv["reset_value"] = raw[128]
        if len(raw) >= 148 and _u64(raw, 140):
            inv["dsdt"] = _u64(raw, 140)

    def hpet(self, raw: bytes) -> None:
        if len(raw) < 56:
            raise AcpiError("HPET lacks its 56-byte prefix")
        self.inventory.update(hpet_id=_u32(raw, 36), hpet_gas=_gas(raw, 40),
                              hpet_number=raw[52], hpet_min_tick=_u16(raw, 53),
                              hpet_page_protection=raw[55])

    def mcfg(self, raw: bytes) -> None:
        if len(raw) < 44 or (len(raw) - 44) % 16:
            raise AcpiError("MCFG has a short header or partial allocation")
        records = self.inventory["mcfg_regions"]
        for offset in range(44, len(raw), 16):
            start, end = raw[offset + 10:offset + 12]
            if start > end:
                raise AcpiError("MCFG bus interval is reversed")
            records.append(dict(base=_u64(raw, offset), segment=_u16(raw, offset + 8),
                                start_bus=start, end_bus=end))
        self.inventory["mcfg_count"] = len(records)

    def run(self, rsdp: int) -> dict:
        first = self.read(rsdp, 20)
        if first[:8] != b"RSD PTR " or sum(first) & 255:
            raise AcpiError("invalid RSDP signature or legacy checksum")
        if first[15] < 2:
            raise AcpiError("RSDP2/XSDT required by this reference profile")
        prefix = self.read(rsdp, 36)
        length = _u32(prefix, 20)
        if length < 36 or length > 4096:
            raise AcpiError("RSDP length outside supported 36..4096 range")
        raw = self.read(rsdp, length)
        if raw[:20] != first or raw[:36] != prefix or sum(raw) & 255:
            raise AcpiError("RSDP changed or has an invalid extended checksum")
        self.remember(rsdp, raw, "RSD PTR ")
        inv = self.inventory
        inv.update(rsdp=rsdp, rsdp_revision=raw[15], xsdt=_u64(raw, 24))
        xsdt = self.sdt(inv["xsdt"])
        if xsdt[:4] != b"XSDT" or (len(xsdt) - 36) % 8:
            raise AcpiError("invalid XSDT signature or entry span")
        count = (len(xsdt) - 36) // 8
        if count > MAX_TABLES:
            raise AcpiError("XSDT exceeds bounded table count")
        inv["table_count"] = count
        seen: set[int] = {rsdp, inv["xsdt"]}
        handlers = {b"APIC": ("madt", self.madt), b"FACP": ("fadt", self.fadt),
                    b"HPET": ("hpet", self.hpet), b"MCFG": ("mcfg", self.mcfg)}
        for offset in range(36, len(xsdt), 8):
            address = _u64(xsdt, offset)
            if address in seen:
                raise AcpiError("repeated/cyclic XSDT table address")
            seen.add(address)
            table = self.sdt(address)  # Unknown signatures still require the full checksum.
            handler = handlers.get(table[:4])
            if handler is not None:
                key, parse = handler
                if inv[key]:
                    # The logical Inventory has one slot. HPET's specification
                    # permits more tables; this is an explicit profile capacity.
                    raise AcpiError(f"multiple {table[:4].decode()} tables exceed one-slot inventory")
                inv[key] = address
                parse(table)
        if not inv["madt"] or not inv["fadt"]:
            raise AcpiError("x86 APIC inventory requires MADT and FADT")
        return inv


def discover(read: PhysicalReader, rsdp: int) -> dict:
    """Decode raw physical ACPI into Inventory-named logical values.

    All CPU type 0/9 records are kept, including disabled entries. ``table_count``
    counts every XSDT entry, including unknown tables. Absent HPET/MCFG and absent
    optional FADT tail fields remain zero/empty. GAS dictionaries preserve raw
    firmware bytes; no legacy PM-timer GAS is invented. DSDT prefers nonzero
    X_DSDT when the complete field exists. MMIO/IO addresses are never read.
    """
    return _Discovery(read).run(rsdp)


def discover_with_tables(read: PhysicalReader, rsdp: int) -> dict:
    """Additionally return each checked RSDP/SDT physical span and SHA-256."""
    parser = _Discovery(read)
    return dict(inventory=parser.run(rsdp), tables=parser.tables)
