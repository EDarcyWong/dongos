#!/usr/bin/env python3
"""Build the version 1 DongOS image and its loader-bound SHA-256 manifest.

The dependency-free encoder emits a valid LZ4 block containing one literal
sequence. It deliberately does not reduce the payload size yet. The decoder
accepts normal LZ4 matches too, so a future compressor need not change the ABI.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import struct

MAGIC = b"DONGIMG1"
VERSION = 1
HEADER_SIZE = 80
KERNEL_BASE = 0xFFFFFFFF80000000
MAX_RAW_SIZE = 2 * 1024 * 1024
MAX_FILE_SIZE = 4 * 1024 * 1024
HEADER = struct.Struct("<8sIIQQQQQ24s")


def lz4_encode(raw: bytes) -> bytes:
    """Encode one standards-compliant literal-only LZ4 block."""
    size = len(raw)
    result = bytearray([min(size, 15) << 4])
    if size >= 15:
        extra = size - 15
        while extra >= 255:
            result.append(255)
            extra -= 255
        result.append(extra)
    result.extend(raw)
    return bytes(result)


def lz4_decode(block: bytes, raw_size: int) -> bytes:
    """Decode a bounded independent LZ4 block, including overlapping matches."""
    if not 0 <= raw_size <= MAX_RAW_SIZE:
        raise ValueError("invalid LZ4 output size")
    result = bytearray()
    cursor = 0
    matched = False

    def length(base: int) -> int:
        nonlocal cursor
        value = base
        if base == 15:
            while True:
                if cursor == len(block):
                    raise ValueError("truncated LZ4 length")
                extra = block[cursor]
                cursor += 1
                value += extra
                if value > MAX_RAW_SIZE:
                    raise ValueError("LZ4 length exceeds output limit")
                if extra != 255:
                    break
        return value

    while cursor < len(block):
        token = block[cursor]
        cursor += 1
        literals = length(token >> 4)
        if literals > len(block) - cursor or literals > raw_size - len(result):
            raise ValueError("LZ4 literals exceed buffer")
        result.extend(block[cursor:cursor + literals])
        cursor += literals
        if cursor == len(block):
            if len(result) != raw_size or (matched and literals < 5):
                raise ValueError("invalid LZ4 final literals or output size")
            return bytes(result)
        if len(block) - cursor < 2:
            raise ValueError("truncated LZ4 offset")
        offset = block[cursor] | block[cursor + 1] << 8
        cursor += 2
        if offset == 0 or offset > len(result):
            raise ValueError("invalid LZ4 offset")
        match = length(token & 15) + 4
        if raw_size - len(result) < 12 or match > raw_size - len(result):
            raise ValueError("LZ4 match exceeds buffer or final-match limit")
        matched = True
        for _ in range(match):
            result.append(result[-offset])
    raise ValueError("missing LZ4 final literal sequence")


def parse_header(image: bytes) -> tuple[int, int]:
    """Validate every v1 header field and return (compressed_size, raw_size)."""
    if not HEADER_SIZE <= len(image) <= MAX_FILE_SIZE:
        raise ValueError("image size outside allowed range")
    magic, version, header_size, packed, raw, base, entry, flags, reserved = HEADER.unpack_from(image)
    if (magic != MAGIC or version != VERSION or header_size != HEADER_SIZE
            or packed == 0 or packed != len(image) - HEADER_SIZE
            or not 1 <= raw <= MAX_RAW_SIZE or base != KERNEL_BASE
            or entry != 0 or flags != 1 or reserved != bytes(24)):
        raise ValueError("invalid DongOS v1 image header")
    return packed, raw


def pack_image(raw: bytes) -> bytes:
    if not 1 <= len(raw) <= MAX_RAW_SIZE:
        raise ValueError("kernel must contain 1 byte through 2 MiB")
    block = lz4_encode(raw)
    header = HEADER.pack(MAGIC, VERSION, HEADER_SIZE, len(block), len(raw),
                         KERNEL_BASE, 0, 1, bytes(24))
    return header + block


def unpack_image(image: bytes, expected_hash: bytes | None = None) -> bytes:
    """Host-side reference for strict header, whole-file hash and LZ4 checks."""
    _, raw_size = parse_header(image)
    if expected_hash is not None and hashlib.sha256(image).digest() != expected_hash:
        raise ValueError("image SHA-256 mismatch")
    return lz4_decode(image[HEADER_SIZE:], raw_size)


def manifest_text(image: bytes) -> str:
    _, raw_size = parse_header(image)
    digest = ", ".join(f"0x{byte:02x}" for byte in hashlib.sha256(image).digest())
    return ("; Generated by tools/mkimage.py; SHA-256 covers the complete image.\n"
            f"%define IMAGE_FILE_SIZE {len(image)}\n"
            f"%define IMAGE_RAW_SIZE {raw_size}\n"
            "%define IMAGE_ENTRY_OFFSET 0\n"
            f"%define IMAGE_KERNEL_BASE 0x{KERNEL_BASE:016x}\n"
            f"%define IMAGE_HEADER_SIZE {HEADER_SIZE}\n"
            f"%define IMAGE_EXPECTED_HASH_BYTES {digest}\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("kernel", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--manifest", required=True, type=Path)
    args = parser.parse_args()
    try:
        image = pack_image(args.kernel.read_bytes())
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.manifest.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(image)
        args.manifest.write_text(manifest_text(image), encoding="ascii")
    except (OSError, ValueError) as exc:
        parser.exit(1, f"mkimage: {exc}\n")
    print(f"Built {args.output}: {len(image)} bytes (LZ4 literal block, no size reduction)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
