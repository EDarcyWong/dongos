"""Freeze Python's Dong v0.1 identifier properties; not a target dependency.

Run from the repository root with the documented Unicode 15.0.0 Python runtime.
The emitted Dong module contains data and scalar functions only.
"""
from pathlib import Path
import argparse
import hashlib
import unicodedata

ROOT = Path(__file__).resolve().parent
PROPERTIES = (
    ("START", lambda c: c.isidentifier()),
    ("CONTINUE", lambda c: ("a" + c).isidentifier()),
    ("SPACE", lambda c: c.isspace()),
    ("ALNUM", lambda c: c.isalnum()),
)


def ranges(predicate):
    result, lower = [], None
    for cp in range(0x110000):
        if predicate(chr(cp)):
            if lower is None:
                lower = cp
        elif lower is not None:
            result.append((lower, cp - 1))
            lower = None
    if lower is not None:
        result.append((lower, 0x10ffff))
    return result


def generate():
    lines = [
        "// Generated by lang/bootstrap/gen_unicode.py; do not edit tables by hand.",
        f"// Unicode {unicodedata.unidata_version}; Python str.isidentifier, continuation, isspace, isalnum.",
        "// Each range is (lower << 21) | upper; surrogate code points never match.",
        "module bootstrap.unicode;",
        f'pub const VERSION:[]const u8="{unicodedata.unidata_version}";',
    ]
    for name, predicate in PROPERTIES:
        entries = ranges(predicate)
        values = [f"0x{((lo << 21) | hi):x}" for lo, hi in entries]
        lines += [f"const {name}:[{len(values)}]u64=["]
        lines += [" ".join(value + "," for value in values[i:i + 6]) for i in range(0, len(values), 6)]
        api_name = {"START": "id_start", "CONTINUE": "id_continue", "SPACE": "space", "ALNUM": "alnum"}[name]
        lines += ["];", f"pub fn {api_name}(cp:u32)bool{{return contains({name}[..],cp);}}"]
    lines += [
        "fn contains(table:[]const u64,cp:u32)bool{",
        " var lo:usize=0;var hi:usize=table.len;let value=cp as u64;",
        " while lo<hi{let mid=lo+(hi-lo)/2;let range=table[mid];",
        "  if value<(range>>21){hi=mid;}else if value>(range&0x1f_ffff){lo=mid+1;}else{return true;}",
        " }return false;",
        "}",
        "pub struct Decoded{pub cp:u32,pub bytes:usize}",
        "pub const EMPTY:Decoded=Decoded{cp:0,bytes:0};",
        "// Strict UTF-8: rejects overlong encodings, surrogates, >U+10FFFF and truncation.",
        "// The caller owns readable source and writable out; failure does not modify out.",
        "pub unsafe fn decode(source:[]const u8,at:usize,out:*Decoded)bool{unsafe{",
        " if at>=source.len||out==null{return false;}let a=source[at];",
        " if a<128{*out=Decoded{cp:a as u32,bytes:1};return true;}",
        " var count:usize=0;var cp:u32=0;",
        " if a>=0xc2&&a<=0xdf{count=2;cp=(a&31) as u32;}",
        " else if a>=0xe0&&a<=0xef{count=3;cp=(a&15) as u32;}",
        " else if a>=0xf0&&a<=0xf4{count=4;cp=(a&7) as u32;}else{return false;}",
        " if count>source.len-at{return false;}let b=source[at+1];",
        " if b<0x80||b>0xbf||(a==0xe0&&b<0xa0)||(a==0xed&&b>=0xa0)",
        "  ||(a==0xf0&&b<0x90)||(a==0xf4&&b>=0x90){return false;}",
        " var i:usize=1;while i<count{let part=source[at+i];if part<0x80||part>0xbf{return false;}",
        "  cp=(cp<<6)|(part&63) as u32;i+=1;}",
        " *out=Decoded{cp:cp,bytes:count};return true;",
        "}}",
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    if unicodedata.unidata_version != "15.0.0":
        raise SystemExit("generation requires Unicode 15.0.0; do not silently change the language tables")
    content = generate()
    path = ROOT / "unicode.dg"
    if options.check:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            raise SystemExit("frozen Unicode module differs from generator")
    else:
        path.write_text(content, encoding="utf-8", newline="\n")
    print(f"Unicode {unicodedata.unidata_version}: {hashlib.sha256(content.encode()).hexdigest()}")


if __name__ == "__main__":
    main()
