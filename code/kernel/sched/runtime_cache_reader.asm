; Future privileged reader and real native-testable drawing gate. SysV ABI.
; No PAT/MTRR writes, PGE emulation, CR3 switch or hidden global storage.
bits 64
default rel
global runtime_cache_gate_enter,runtime_cache_gate_leave,runtime_cache_gate_close
global runtime_cache_gate_drain,runtime_cache_gate_open,runtime_cache_hardware
extern user_smp_arch_cpu
section .text
; Gate = {word(closed bit63, writer count0..31), epoch, drained, opened}.
; Enter/leave return 1 only when the corresponding ownership was acquired or
; released. Every failed close/open leaves a closed gate closed.
runtime_cache_gate_enter:
    mov rax,[rdi]
.retry:
    test rax,rax
    js .no
    mov rdx,rax
    shr rdx,32
    jnz .no
    cmp eax,-1
    je .no
    lea rdx,[rax+1]
    lock cmpxchg [rdi],rdx
    jne .retry
    mov eax,1
    ret
.no:
    xor eax,eax
    ret
runtime_cache_gate_leave:
    mov rax,[rdi]
.retry:
    mov edx,eax
    test edx,edx
    jz .no
    mov r8,rax
    btr r8,63
    btr r8,62
    shr r8,32
    jnz .no
    lea rdx,[rax-1]
    lock cmpxchg [rdi],rdx
    jne .retry
    mov eax,1
    ret
.no:
    xor eax,eax
    ret
runtime_cache_gate_close:
    test rsi,rsi
    jz .no
    mov r8,[rdi+8]
    lea r9,[r8+1]
    cmp r9,rsi
    jne .no
    mov rax,[rdi]
.retry:
    test rax,rax
    js .no
    mov rdx,rax
    shr rdx,32
    jnz .no
    mov rdx,rax
    bts rdx,63
    bts rdx,62                    ; unpublished closing state
    lock cmpxchg [rdi],rdx
    jne .retry
    mov rax,r8
    lock cmpxchg [rdi+8],rsi
    jne .no                      ; gate remains closed even on corruption
    mov qword [rdi+16],0
    lock btr qword [rdi],62       ; publish epoch/drained before drain can pass
    mov eax,1
    ret
.no:
    xor eax,eax
    ret
runtime_cache_gate_drain:
    mov rax,0x8000000000000000
    cmp [rdi],rax
    jne .no
    test rsi,rsi
    jz .no
    cmp [rdi+8],rsi
    jne .no
    xor eax,eax
    lock cmpxchg [rdi+16],rsi
    jne .no
    mov eax,1
    ret
.no:
    xor eax,eax
    ret
runtime_cache_gate_open:
    test rsi,rsi
    jz .no
    cmp [rdi+8],rsi
    jne .no
    cmp [rdi+16],rsi
    jne .no
    mov rax,0x8000000000000000
    cmp [rdi],rax
    jne .no
    mov rax,[rdi+24]
    cmp rax,rsi
    jae .no
    lock cmpxchg [rdi+24],rsi      ; only one opener can publish this token
    jne .no
    mov rax,0x8000000000000000
    xor edx,edx
    lock cmpxchg [rdi],rdx
    jne .no
    mov eax,1
    ret
.no:
    xor eax,eax
    ret
; Hardware(action, request, completed-alltag-sequence, Reading*).
; Reading's 57 qwords are generated by actual local instructions. This entry
; is assembled in host gates but NEVER called by their native C process.
runtime_cache_hardware:
    push rbx
    push rbp
    push r12
    push r13
    push r14
    push r15
    sub rsp,8
    mov r12,rcx
    mov r13,rdi
    mov r14,rsi
    mov r15,rdx
    cmp r13,1
    jb .bad
    cmp r13,2
    ja .bad
    mov rdi,r12
    xor eax,eax
    mov ecx,57
    cld
    rep stosq
    pushfq
    pop rax
    test eax,0x200
    jnz .bad
    mov qword [r12+8],1
    mov rax,cr3
    test rax,4095
    jnz .bad
    mov [r12+16],rax
    mov rax,cr0
    mov [r12+24],rax
    test eax,0x60000000
    jnz .bad
    mov rax,cr4
    mov [r12+32],rax
    test eax,128
    jnz .bad
    call user_smp_arch_cpu
    mov [r12],rax
    mov eax,1
    cpuid
    mov eax,edx
    and eax,(1<<12)|(1<<16)
    cmp eax,(1<<12)|(1<<16)
    jne .bad
    shr ebx,24
    mov [r12+104],rbx
    mov eax,0x80000000
    cpuid
    cmp eax,0x80000008
    jb .bad
    mov eax,0x80000008
    cpuid
    movzx eax,al
    cmp eax,32
    jb .bad
    cmp eax,52
    ja .bad
    mov [r12+48],rax
    cmp r13,2
    jne .capture
    sfence
    wbinvd
    mov qword [r12+96],3
.capture:
    mov ecx,0x277
    rdmsr
    shl rdx,32
    or rax,rdx
    mov [r12+40],rax
    mov ecx,0xfe
    rdmsr
    shl rdx,32
    or rax,rdx
    mov [r12+56],rax
    movzx ebp,al
    cmp ebp,16
    ja .bad
    shl ebp,1
    mov ecx,0x2ff
    rdmsr
    shl rdx,32
    or rax,rdx
    mov [r12+64],rax
    xor r8d,r8d
.variable:
    cmp r8d,ebp
    jae .fixed_begin
    lea ecx,[r8d+0x200]
    rdmsr
    shl rdx,32
    or rax,rdx
    mov [r12+112+r8*8],rax
    inc r8d
    jmp .variable
.fixed_begin:
    test qword [r12+56],1<<8
    jz .ready
    xor r8d,r8d
.fixed:
    ; Fixed MSRs: 0x250,0x258,0x259,0x268..0x26f.
    mov ecx,0x250
    test r8d,r8d
    jz .read_fixed
    lea ecx,[r8d+0x257]
    cmp r8d,3
    jb .read_fixed
    lea ecx,[r8d+0x265]
.read_fixed:
    rdmsr
    shl rdx,32
    or rax,rdx
    mov [r12+368+r8*8],rax
    inc r8d
    cmp r8d,11
    jb .fixed
.ready:
    mov [r12+72],r14
    mov [r12+80],r15
    mov [r12+88],r13
    xor eax,eax
    jmp .return
.bad:
    mov eax,1
.return:
    add rsp,8
    pop r15
    pop r14
    pop r13
    pop r12
    pop rbp
    pop rbx
    ret
